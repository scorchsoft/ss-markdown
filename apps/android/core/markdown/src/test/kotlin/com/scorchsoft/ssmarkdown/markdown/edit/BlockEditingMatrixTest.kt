package com.scorchsoft.ssmarkdown.markdown.edit

import com.scorchsoft.ssmarkdown.markdown.edit.BlockEditingMatrix.Action
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File

/**
 * Runs [BlockEditingMatrix] through the edit commands Code uses, and keeps
 * Preview's copy of it (`block-editing.json`) in step: the page's e2e suite
 * drives the same rows through key presses. After changing the matrix, run
 * `gradle -p apps/android :core:markdown:test -Pssmarkdown.updateVectors=true`
 * and commit the JSON with it.
 */
class BlockEditingMatrixTest {
    @Test
    fun `every row of the matrix holds in Code`() {
        val failures =
            BlockEditingMatrix.rows.mapNotNull { row ->
                val actual = runRow(row.action, row.before)
                if (actual ==
                    row.after
                ) {
                    null
                } else {
                    "  ${row.id} (${row.action})\n    want ${show(row.after)}\n    got  ${show(actual)}"
                }
            }
        assertTrue(
            "${failures.size} of ${BlockEditingMatrix.rows.size} rows failed:\n" + failures.joinToString("\n"),
            failures.isEmpty(),
        )
    }

    @Test
    fun `the matrix covers every action and keeps its ids unique`() {
        val rows = BlockEditingMatrix.rows
        assertEquals(rows.size, rows.map { it.id }.toSet().size)
        assertEquals(Action.entries.toSet(), rows.map { it.action }.toSet())
    }

    @Test
    fun `Preview's copy of the matrix is current`() {
        val generated = vectorsJson()
        if (System.getProperty("ssmarkdown.updateVectors") == "true") {
            VECTORS.writeText(generated)
        }
        assertTrue("missing ${VECTORS.absolutePath}", VECTORS.exists())
        assertEquals(
            "block-editing.json is stale: run :core:markdown:test -Pssmarkdown.updateVectors=true",
            generated,
            VECTORS.readText(),
        )
    }

    /** A row's action as the editor performs it: Backspace that the command leaves alone deletes a char. */
    private fun runRow(
        action: Action,
        before: String,
    ): String {
        if (action != Action.Backspace) return run(BlockEditingMatrix.command(action), before)
        val (text, selection) = marked(before)
        val result = EditCommand.BackspaceAtItemStart.apply(text, selection)
        if (!result.isNoOp) {
            val after = result.applyTo(text)
            assertInvariants(text, result, after)
            return render(after, result.selection)
        }
        val at = selection.start
        return render(text.removeRange(at - 1, at), TextSelection.caret(at - 1))
    }

    private fun show(s: String): String = '"' + s.replace("\n", "⏎") + '"'

    companion object {
        private val VECTORS = File("../../feature/preview/web/test/vectors/block-editing.json")

        fun vectorsJson(): String =
            buildString {
                append("{\n")
                append(
                    "  \"comment\": \"Generated by core:markdown BlockEditingMatrixTest from BlockEditingMatrix.kt. ",
                )
                append("Do not edit.\",\n")
                append("  \"rows\": [\n")
                val rows = BlockEditingMatrix.rows.filter { it.preview }
                rows.forEachIndexed { i, row ->
                    append("    {")
                    append("\"id\": ").append(quote(row.id))
                    append(", \"action\": ").append(quote(row.action.wire))
                    append(", \"before\": ").append(quote(row.before))
                    append(", \"after\": ").append(quote(row.previewAfter ?: row.after))
                    append("}")
                    append(if (i < rows.size - 1) ",\n" else "\n")
                }
                append("  ]\n}\n")
            }

        private fun quote(s: String): String =
            buildString {
                append('"')
                for (c in s) {
                    when (c) {
                        '"' -> append("\\\"")
                        '\\' -> append("\\\\")
                        '\n' -> append("\\n")
                        '\t' -> append("\\t")
                        else -> append(c)
                    }
                }
                append('"')
            }
    }
}
