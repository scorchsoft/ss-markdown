package com.scorchsoft.ssmarkdown.theme.css

import com.scorchsoft.ssmarkdown.theme.PaletteKey
import com.scorchsoft.ssmarkdown.theme.Theme
import com.scorchsoft.ssmarkdown.theme.ThemeVariant
import java.util.Locale
import kotlin.math.pow

/**
 * Turns a [Theme] into the CSS the preview bundle consumes: `@font-face`
 * rules for the theme's fonts, one `:root` block of `--ssm-*` custom
 * properties, then the theme's own Advanced CSS. The preview's stylesheet
 * is written only against these variables, so swapping a theme is
 * swapping one `<style>` element. The contract is THEME-CSS.md in this
 * module; change both together.
 */
public object ThemeCss {
    /** h4 is body size; h5 and h6 step below it as GitHub's do. */
    private const val H5_EM = 0.875
    private const val H6_EM = 0.85
    private const val CODE_EM = 0.875
    private const val H1_POWER = 3
    private const val H2_POWER = 2
    private val decimals = Regex("""\.?0+$""")

    /** The full stylesheet for [theme] in [variant]. */
    public fun stylesheet(
        theme: Theme,
        variant: ThemeVariant,
        fonts: FontFaceSource = FontFaceSource.None,
    ): String =
        buildString {
            append("/* SS Markdown theme: ").append(comment(theme.name)).append(" (").append(variant.cssColorScheme)
            append("). Generated by core/theme; see THEME-CSS.md. */\n")
            append(fontFaces(theme, fonts))
            append(variables(theme, variant, fonts))
            if (theme.css.isNotBlank()) append("/* Advanced CSS */\n").append(theme.css.trim()).append('\n')
        }

    /** `@font-face` rules for every face of the theme's three families, each family once. */
    public fun fontFaces(
        theme: Theme,
        fonts: FontFaceSource,
    ): String =
        listOf(theme.fonts.body, theme.fonts.heading, theme.fonts.code)
            .distinct()
            .flatMap { fonts.faces(it) }
            .joinToString("") { fontFace(it) }

    /** The `:root` block of custom properties. */
    public fun variables(
        theme: Theme,
        variant: ThemeVariant,
        fonts: FontFaceSource = FontFaceSource.None,
    ): String {
        val palette = theme.palette(variant)
        val scale = theme.size.headingScale
        val properties =
            PaletteKey.entries.map { it.cssVariable to palette[it].hex } +
                listOf(
                    "--ssm-font-body" to stack(theme.fonts.body, fonts.generic(theme.fonts.body)),
                    "--ssm-font-heading" to stack(theme.fonts.heading, fonts.generic(theme.fonts.heading)),
                    "--ssm-font-code" to stack(theme.fonts.code, GenericFamily.MONOSPACE),
                    "--ssm-size-base" to number(theme.size.base) + "px",
                    "--ssm-line-height" to number(theme.size.lineHeight),
                    "--ssm-heading-scale" to number(scale),
                    "--ssm-h1" to number(scale.pow(H1_POWER)) + "em",
                    "--ssm-h2" to number(scale.pow(H2_POWER)) + "em",
                    "--ssm-h3" to number(scale) + "em",
                    "--ssm-h4" to "1em",
                    "--ssm-h5" to number(H5_EM) + "em",
                    "--ssm-h6" to number(H6_EM) + "em",
                    "--ssm-code-size" to number(CODE_EM) + "em",
                )
        return buildString {
            append(":root {\n  color-scheme: ").append(variant.cssColorScheme).append(";\n")
            properties.forEach { (name, value) ->
                append("  ")
                    .append(name)
                    .append(": ")
                    .append(value)
                    .append(";\n")
            }
            append("}\n")
        }
    }

    /** A font stack: the quoted family, then its generic fallback. */
    public fun stack(
        family: String,
        generic: GenericFamily,
    ): String = "${quote(family)}, ${generic.css}"

    private fun fontFace(face: FontFace): String {
        val (low, high) = face.weights.first to face.weights.last
        val weight = if (low == high) "$low" else "$low $high"
        return "@font-face { font-family: ${quote(face.family)}; " +
            "src: url(${quote(face.url)}) format(\"${face.format.css}\"); " +
            "font-style: ${if (face.italic) "italic" else "normal"}; font-weight: $weight; font-display: swap; }\n"
    }

    /** A CSS string literal. Escapes anything that could end it or the rule. */
    private fun quote(text: String): String =
        buildString {
            append('"')
            for (c in text) {
                when (c) {
                    '"', '\\' -> append('\\').append(c)
                    '\n', '\r', '\u000C' -> append("\\A ")
                    '<' -> append("\\3C ")
                    else -> append(c)
                }
            }
            append('"')
        }

    private fun comment(text: String): String = text.replace("*/", "* /")

    /** At most four decimals, trailing zeros dropped, always a `.` separator. */
    private fun number(value: Double): String {
        val fixed = String.format(Locale.ROOT, "%.4f", value)
        return if ('.' in fixed) fixed.replace(decimals, "") else fixed
    }
}
