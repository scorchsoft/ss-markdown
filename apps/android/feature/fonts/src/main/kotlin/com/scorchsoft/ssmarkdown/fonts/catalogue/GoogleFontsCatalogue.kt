package com.scorchsoft.ssmarkdown.fonts.catalogue

import com.scorchsoft.ssmarkdown.fonts.FontCategory
import com.scorchsoft.ssmarkdown.fonts.FontStyleKey
import java.io.Reader

/**
 * One Google Fonts family the picker can offer.
 *
 * @property family the family name, exactly as the CSS2 API expects it.
 * @property category its category.
 * @property styles the styles the app downloads: regular and bold,
 *   upright and italic, where the family has them. Never empty.
 * @property approxKb a size estimate for the picker row ("310 KB") before
 *   anything is fetched; the real size is reported after download.
 */
data class CatalogueEntry(
    val family: String,
    val category: FontCategory,
    val styles: List<FontStyleKey>,
    val approxKb: Int,
)

/**
 * The Google Fonts families with a Latin subset, shipped in the APK as
 * `assets/fonts/google-fonts.tsv` (generated by `tools/fetch-fonts.sh
 * --catalogue` from Google's public metadata). The app never fetches the
 * list itself: searching works offline and leaks nothing about what
 * someone is looking for.
 *
 * The file is tab-separated rather than JSON: 1,800 rows stream-parse in
 * a few milliseconds with no JSON dependency, and diffs stay one line per
 * family.
 *
 * @property entries in popularity order, most popular first.
 */
class GoogleFontsCatalogue(
    val entries: List<CatalogueEntry>,
) {
    private val byName = entries.associateBy { it.family.lowercase() }

    /** The entry for [family] (case-insensitive), or null. */
    fun find(family: String): CatalogueEntry? = byName[family.trim().lowercase()]

    /**
     * Families matching [query], optionally in one [category]: names that
     * start with the query first, then names containing it, each in
     * popularity order. A blank query lists the most popular.
     */
    fun search(
        query: String,
        category: FontCategory? = null,
        limit: Int = DEFAULT_LIMIT,
    ): List<CatalogueEntry> {
        val needle = query.trim().lowercase()
        val pool = entries.asSequence().filter { category == null || it.category == category }
        if (needle.isEmpty()) return pool.take(limit).toList()
        val (prefix, rest) =
            pool
                .filter {
                    needle in it.family.lowercase()
                }.partition { it.family.lowercase().startsWith(needle) }
        return (prefix + rest).take(limit)
    }

    companion object {
        /** The asset path. */
        const val ASSET: String = "fonts/google-fonts.tsv"

        private const val DEFAULT_LIMIT = 50
        private const val COLUMNS = 4
        private const val SIZE_COLUMN = 3

        /** Parses the catalogue file; comments and malformed rows are skipped. */
        fun parse(reader: Reader): GoogleFontsCatalogue =
            GoogleFontsCatalogue(
                reader.useLines { lines ->
                    lines
                        .filterNot { it.isBlank() || it.startsWith("#") }
                        .mapNotNull { row(it.split('\t')) }
                        .toList()
                },
            )

        private fun row(cells: List<String>): CatalogueEntry? {
            if (cells.size != COLUMNS) return null
            val category = FontCategory.fromKey(cells[1])
            val styles = cells[2].split(',').mapNotNull { FontStyleKey.parse(it) }
            val kb = cells[SIZE_COLUMN].toIntOrNull()
            val family = cells[0].takeIf { it.isNotBlank() && styles.isNotEmpty() }
            return if (category == null || kb == null ||
                family == null
            ) {
                null
            } else {
                CatalogueEntry(family, category, styles, kb)
            }
        }
    }
}
