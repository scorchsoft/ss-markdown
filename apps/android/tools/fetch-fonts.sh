#!/usr/bin/env bash
# Fetches SS Markdown's bundled fonts from the google/fonts repository at a
# pinned commit, verifies each download against a pinned SHA-256, subsets
# where the licence allows, and writes them plus MANIFEST.tsv into
# feature/fonts/src/main/assets/fonts/bundled/.
#
#   apps/android/tools/fetch-fonts.sh              # fetch, verify, subset, write
#   apps/android/tools/fetch-fonts.sh --catalogue  # also regenerate google-fonts.tsv
#
# Run from anywhere. Needs curl, sha256sum (or shasum) and python3 (for
# fontTools, installed into a throwaway venv at a pinned version).
#
# Licences: every family is SIL OFL 1.1. Subsetting is a modification under
# the OFL, and a modified font may not use a Reserved Font Name. Lora ("Lora")
# and IBM Plex Sans ("Plex") declare one, so they are shipped byte-for-byte
# as upstream publishes them and never subset. The OFL texts are copied
# next to the fonts and listed in the root NOTICE file.
set -euo pipefail

COMMIT=6c1dbe27dcf7d817d4b62cec033ba77fa8e2a5ec # google/fonts main, 2026-11-01
FONTTOOLS_VERSION=4.68.0
BUDGET_BYTES=3000000 # bundle only if the whole set fits (docs/quality-bar.md, APK size)
# Latin-1, Latin Extended bits used by Western European languages, general
# punctuation, currency, arrows, minus, check marks and the replacement char.
UNICODES="U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2190-2199,U+2212,U+2215,U+2713,U+2714,U+2717,U+FEFF,U+FFFD"

# family | upstream path under ofl/ | output file | italic | wght min | wght max | upstream sha256 | subset
PINS='
Inter|inter/Inter[opsz,wght].ttf|inter.ttf|0|100|900|29160a80ff49ddcab2c97711247e08b1fab27a484a329ce8b813d820dc559031|yes
Inter|inter/Inter-Italic[opsz,wght].ttf|inter-italic.ttf|1|100|900|acd98e64795781b2058f07b18475e0ecee2a0fe2b42a49e2f9e37d0d6bf66ce6|yes
JetBrains Mono|jetbrainsmono/JetBrainsMono[wght].ttf|jetbrains-mono.ttf|0|100|800|48715a42ec242c21e9f02692891e147d022299a52e48d5e413e1a942193ffeda|yes
JetBrains Mono|jetbrainsmono/JetBrainsMono-Italic[wght].ttf|jetbrains-mono-italic.ttf|1|100|800|85ae2a5cd3f56baf1ce1c21a851322c58e3d8fbe8e8ad4a4d090a820dd7fe558|yes
Source Serif 4|sourceserif4/SourceSerif4[opsz,wght].ttf|source-serif-4.ttf|0|200|900|97b2d4da6e3cb494b5a1e66ae176914d852ccabef49e0c02c0df25f3e39aca0b|yes
Source Serif 4|sourceserif4/SourceSerif4-Italic[opsz,wght].ttf|source-serif-4-italic.ttf|1|200|900|15fbc7e4679489a501998c3669272637a6646388ef7e4bd77eebb5bf967a1f42|yes
Literata|literata/Literata[opsz,wght].ttf|literata.ttf|0|200|900|b41138c9373112f32abb589cc22e8674b06ed4048b0c513be922bdd26f274440|yes
Literata|literata/Literata-Italic[opsz,wght].ttf|literata-italic.ttf|1|200|900|d483dfaeba9cbf4ce71d32a52ee65df82f7e35b15fff8d1011cdb242d1fcd465|yes
Lora|lora/Lora[wght].ttf|lora.ttf|0|400|700|822a6621ccbe8d97d20ac88c1c41f5615c9c2c202eaa75f272cd452aac6475a7|no
Lora|lora/Lora-Italic[wght].ttf|lora-italic.ttf|1|400|700|22d8d8854b53807aa664ca34f2031a9ed57a1d0dea296b8b96cdd3aad937a2b3|no
IBM Plex Sans|ibmplexsans/IBMPlexSans[wdth,wght].ttf|ibm-plex-sans.ttf|0|100|700|3b031aa4216174205bd8471f88a49b91f093169e9e87bd5262242bc5967fe2e3|no
IBM Plex Sans|ibmplexsans/IBMPlexSans-Italic[wdth,wght].ttf|ibm-plex-sans-italic.ttf|1|100|700|0b94c5e981993764db32bf9c610ecc60cbd34ad77ec2f10ba03c64ab75124d8e|no
Atkinson Hyperlegible Next|atkinsonhyperlegiblenext/AtkinsonHyperlegibleNext[wght].ttf|atkinson-hyperlegible-next.ttf|0|200|800|5a455d1cfa099b601ab70751bb9673e8fe1854dc4500c80e1a220d0d75e31745|yes
Atkinson Hyperlegible Next|atkinsonhyperlegiblenext/AtkinsonHyperlegibleNext-Italic[wght].ttf|atkinson-hyperlegible-next-italic.ttf|1|200|800|ce9cffed32742ad2d9238c561a93220385e5934cdc02b8eb4097a50efa957dc6|yes
Fira Code|firacode/FiraCode[wght].ttf|fira-code.ttf|0|300|700|9335b082b3c7850d98a64b584f3417f65355f3471278bb5eeb8c6c0e8657aeeb|yes
'

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ASSETS="$HERE/../feature/fonts/src/main/assets/fonts"
OUT="$ASSETS/bundled"
LICENCES="$ASSETS/licences"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

sha256() { if command -v sha256sum >/dev/null; then sha256sum "$1" | cut -d' ' -f1; else shasum -a 256 "$1" | cut -d' ' -f1; fi; }
fetch() { curl -fsSL --retry 3 --retry-delay 2 -o "$2" "$1"; }
raw() { echo "https://raw.githubusercontent.com/google/fonts/$COMMIT/ofl/$(echo "$1" | sed 's/\[/%5B/g; s/\]/%5D/g; s/,/%2C/g')"; }

echo "Installing fontTools $FONTTOOLS_VERSION into a temporary venv..."
python3 -m venv "$WORK/venv"
"$WORK/venv/bin/pip" install --quiet "fonttools==$FONTTOOLS_VERSION"

mkdir -p "$OUT" "$LICENCES" "$WORK/in"
MANIFEST="$WORK/MANIFEST.tsv"
{
  echo "# Bundled fonts. Generated by apps/android/tools/fetch-fonts.sh from google/fonts@$COMMIT."
  echo "# file<TAB>family<TAB>italic<TAB>weight min<TAB>weight max<TAB>bytes<TAB>sha256<TAB>subset"
} > "$MANIFEST"

total=0
while IFS='|' read -r family path file italic wmin wmax pinned subset; do
  [ -z "$family" ] && continue
  src="$WORK/in/$file"
  echo "Fetching $path"
  fetch "$(raw "$path")" "$src"
  actual="$(sha256 "$src")"
  if [ "$actual" != "$pinned" ]; then
    echo "Checksum mismatch for $path: expected $pinned, got $actual" >&2
    exit 1
  fi
  if [ "$subset" = "yes" ]; then
    "$WORK/venv/bin/pyftsubset" "$src" --unicodes="$UNICODES" --layout-features='*' --output-file="$OUT/$file"
  else
    cp "$src" "$OUT/$file"
  fi
  dir="${path%%/*}"
  licence="$LICENCES/$dir-OFL.txt"
  [ -f "$licence" ] || fetch "https://raw.githubusercontent.com/google/fonts/$COMMIT/ofl/$dir/OFL.txt" "$licence"
  bytes="$(wc -c < "$OUT/$file" | tr -d ' ')"
  total=$((total + bytes))
  printf '%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' "$file" "$family" "$italic" "$wmin" "$wmax" "$bytes" "$(sha256 "$OUT/$file")" "$subset" >> "$MANIFEST"
done <<< "$PINS"

cp "$MANIFEST" "$OUT/MANIFEST.tsv"

if [ "${1:-}" = "--catalogue" ]; then
  echo "Regenerating the Google Fonts catalogue..."
  fetch "https://fonts.google.com/metadata/fonts" "$WORK/metadata.json"
  python3 -I "$HERE/google_fonts_catalogue.py" "$WORK/metadata.json" "$(date -u +%Y-%m-%d)" > "$ASSETS/google-fonts.tsv"
fi

echo "Total bundled: $total bytes (budget $BUDGET_BYTES)."
if [ "$total" -gt "$BUDGET_BYTES" ]; then
  echo "OVER BUDGET: keep the .ttf files out of git (feature/fonts/.gitignore) until the budget is agreed."
fi
