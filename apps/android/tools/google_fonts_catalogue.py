"""Builds feature/fonts' bundled Google Fonts catalogue (google-fonts.tsv).

Reads the public metadata at https://fonts.google.com/metadata/fonts (saved
to a file by fetch-fonts.sh) and writes one line per open-source family that
has a Latin subset: family, category, the styles the app downloads (regular
and bold, upright and italic, where they exist) and an approximate size.

The app never fetches this list at run time; it ships the file.

Usage: python3 -I google_fonts_catalogue.py metadata.json YYYY-MM-DD > google-fonts.tsv
"""
import json, sys, re
d = json.load(open(sys.argv[1]))
cat = {'Serif':'serif','Sans Serif':'sans','Monospace':'mono','Display':'display','Handwriting':'handwriting'}
rows = []
for f in d['familyMetadataList']:
    if 'latin' not in f['subsets'] or not f.get('isOpenSource', True):
        continue
    if '\t' in f['family'] or not re.fullmatch(r"[A-Za-z0-9 ]+", f['family']):
        continue
    keys = list(f['fonts'].keys())
    upright = sorted(int(k) for k in keys if not k.endswith('i'))
    italic = {int(k[:-1]) for k in keys if k.endswith('i')}
    if not upright:
        continue
    reg = 400 if 400 in upright else min(upright, key=lambda w: abs(w-400))
    styles = [str(reg)]
    if 700 in upright and reg != 700: styles.append('700')
    if reg in italic: styles.append(f'{reg}i')
    if 700 in italic and reg != 700 and '700' in styles: styles.append('700i')
    kb = max(1, round(f['size'] * len(styles) / max(1, len(keys)) / 1024))
    rows.append((f['popularity'], f['family'], cat[f['category']], ','.join(styles), kb))
rows.sort()
print('# Google Fonts catalogue for the font picker. Generated by apps/android/tools/fetch-fonts.sh --catalogue')
print('# from https://fonts.google.com/metadata/fonts on ' + sys.argv[2] + '. Families with a Latin subset only.')
print('# family<TAB>category<TAB>styles (weight, i = italic)<TAB>approx. download KB. Ordered by popularity.')
for _, fam, c, s, kb in rows:
    print(f'{fam}\t{c}\t{s}\t{kb}')
